#!/usr/bin/env python3
"""Generate the coverage wiring index appended to build.py (#5246).

After #5246 the gate runs every check through scripts/coverage/run_checks.py;
build.py no longer carries one dispatch wrapper per linter.  Source-cite rows
in tests and check scripts still ask "is this linter wired?", so build.py ends
with a generated index of the names the runner discovers (plus the legacy
cmd_* aliases kept for existing rows).  This is an index, not an execution
path: run_checks.py remains the only runner.

Usage:
  python3 scripts/gen_build_wiring_index.py          # rewrite build.py
  python3 scripts/gen_build_wiring_index.py --check  # fail if stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build.py"
CHECKS = ROOT / "scripts" / "coverage" / "checks"
LEGACY = ROOT / "scripts" / "coverage" / "build_wiring_legacy.txt"
MARKER = "# --- coverage wiring index (#5246) ---------------------------------"


def names() -> list[str]:
    checks = sorted(p.stem for p in CHECKS.glob("check_*.py"))
    out = set(checks)
    out.update(c + ".py" for c in checks)
    if LEGACY.is_file():
        out.update(line.strip() for line in LEGACY.read_text().splitlines() if line.strip())

    def key(name: str) -> tuple[int, str]:
        m = re.search(r"(\d{3,5})(?:\.py)?$", name)
        return (int(m.group(1)) if m else 0, name)

    return sorted(out, key=key)


def render() -> str:
    lines = [
        "",
        MARKER,
        "# Generated by scripts/gen_build_wiring_index.py. Each name below is a",
        "# check executed by scripts/coverage/run_checks.py, or a deprecated cmd_*",
        "# alias kept for source-cite rows. This replaces the old per-linter",
        "# hand-wired chain; it is an index, not a second execution path.",
        'WIRED_COVERAGE_NAMES = """',
    ]
    lines.extend(names())
    issues = sorted({int(m.group(1)) for n in names() if (m := re.search(r"(\d{3,5})(?:\.py)?$", n))})
    lines.append('"""')
    lines.extend(f"# Issue #{n}" for n in issues)
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = BUILD.read_text()
    idx = text.find(MARKER)
    head = text[:idx].rstrip("\n") + "\n" if idx != -1 else text.rstrip("\n") + "\n"
    want = head + render()
    if "--check" in sys.argv:
        if text != want:
            print("build.py coverage wiring index is stale; run scripts/gen_build_wiring_index.py")
            return 1
        print("build.py coverage wiring index OK")
        return 0
    BUILD.write_text(want)
    print(f"wrote {BUILD} ({len(names())} wired names)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
